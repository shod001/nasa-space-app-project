export const MOON_SCHEDULE = ['m1', 'q1', 'm3', 'm4', 'm5', 'm6', 'm7', 'm8', 'm9', 'm10', 'm11', 'm12', 'm13', 'm14'];
export const MARS_SCHEDULE = ['ms1', 'q1', 'ms3', 'ms4', 'ms5', 'ms6', 'ms7', 'ms8', 'ms9', 'ms10', 'ms11', 'q2', 'ms13', 'ms14'];

export const ALL_EVENTS: Record<string, GameEvent> = {
  ...moon,
  ...mars,
  q1: QUIET_MORNING,
  q2: QUIET_STEADY,
};

export function getEventForDay(location: 'moon' | 'mars', day: number): GameEvent {
  const schedule = location === 'moon' ? MOON_SCHEDULE : MARS_SCHEDULE;
  const id = schedule[Math.min(Math.max(day - 1, 0), schedule.length - 1)];
  return ALL_EVENTS[id] ?? QUIET_MORNING;
}
