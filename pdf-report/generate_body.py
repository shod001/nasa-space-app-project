def make_table(header, rows, ratios, story, cap=None, align_cols=None):
    """header: list[str], rows: list[list[str]], ratios sum to 1.0."""
    col_w = [r * AVAIL_W * 0.98 for r in ratios]
    assert sum(col_w) <= AVAIL_W + 0.5
    data = [[Paragraph('<b>%s</b>' % c, tbl_head) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = tbl_cell_c if (align_cols and i in align_cols) else tbl_cell
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for ri in range(1, len(data)):
        style.append(('BACKGROUND', (0, ri), (-1, ri),
                      TABLE_ROW_ODD if ri % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 12))
    story.append(t)
    if cap:
        story.append(Spacer(1, 6))
        story.append(Paragraph(cap, caption))
    story.append(Spacer(1, 12))


def stat_row(story, stats):
    """stats: list of (value, label). Renders a row of callout boxes."""
    n = len(stats)
    box_w = (AVAIL_W * 0.94) / n
    cells = []
    for val, lab in stats:
        inner = Table(
            [[Paragraph('<b>%s</b>' % val, stat_style)],
             [Paragraph(lab, stat_label)]],
            colWidths=[box_w - 12],
        )
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 8),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 8),
            ('TOPPADDING', (0, 1), (-1, 1), 2),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        cells.append(inner)
    outer = Table([cells], colWidths=[box_w] * n, hAlign='CENTER')
    outer.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(Spacer(1, 8))
    story.append(KeepTogether(outer))
    story.append(Spacer(1, 12))


def embed_image(path, max_width=None, max_height=None):
    if max_width is None:
        max_width = AVAIL_W
    if max_height is None:
        max_height = PAGE_H * 0.35
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


